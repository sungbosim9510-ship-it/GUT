-- 1. 기존 테이블 정리 (초기화 필요 시 사용)
DROP TABLE IF EXISTS mentoring_answers CASCADE;
DROP TABLE IF EXISTS mentoring_requests CASCADE;
DROP TABLE IF EXISTS mentors CASCADE;
DROP TABLE IF EXISTS users CASCADE;


-- 2. 테이블 생성 (Schema Definition)

-- [1] 사용자(회원) 테이블: 멘티 학생 및 동문 멘토 계정
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    role VARCHAR(20) NOT NULL CHECK (role IN ('MENTEE', 'MENTOR')),
    student_id VARCHAR(8) UNIQUE NOT NULL,
    name VARCHAR(50) NOT NULL,
    department VARCHAR(100) NOT NULL,
    grade VARCHAR(20) DEFAULT '2학년',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- [2] 동문 멘토 프로필 테이블: 메인 화면 카드 및 상세 프로필
CREATE TABLE mentors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    name VARCHAR(50) NOT NULL,
    company VARCHAR(100) NOT NULL,
    role_department VARCHAR(150) NOT NULL,
    category VARCHAR(50) NOT NULL CHECK (
        category IN ('all', 'maintenance', 'production', 'quality', 'gas', 'etc')
    ),
    avatar_url TEXT,
    is_verified BOOLEAN DEFAULT true NOT NULL,
    tags JSONB DEFAULT '[]'::jsonb NOT NULL,
    bio TEXT NOT NULL,
    specs TEXT NOT NULL,
    strategy TEXT NOT NULL,
    advice TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- [3] 1:1 멘토링 요청(질문) 테이블: 멘토링 신청 모달 및 요청 게시판
CREATE TABLE mentoring_requests (
    id TEXT PRIMARY KEY DEFAULT ('req-' || floor(extract(epoch from now()) * 1000)::text),
    mentor_id BIGINT REFERENCES mentors(id) ON DELETE CASCADE NOT NULL,
    student_id VARCHAR(8) NOT NULL,
    student_name VARCHAR(50) NOT NULL,
    department VARCHAR(100) NOT NULL,
    grade VARCHAR(20) DEFAULT '2학년' NOT NULL,
    effort TEXT NOT NULL,
    q1 TEXT NOT NULL,
    q2 TEXT,
    status VARCHAR(20) DEFAULT 'pending' NOT NULL CHECK (
        status IN ('pending', 'in_progress', 'completed', 'rejected')
    ),
    applied_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- [4] 멘토링 답변 테이블: 멘토 피드백, 임시저장, 거절 정보
CREATE TABLE mentoring_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id TEXT UNIQUE REFERENCES mentoring_requests(id) ON DELETE CASCADE NOT NULL,
    mentor_id BIGINT REFERENCES mentors(id) ON DELETE CASCADE NOT NULL,
    q1_answer TEXT,
    q2_answer TEXT,
    cheer_message TEXT,
    content TEXT,
    draft JSONB,
    reject_reason_type VARCHAR(50),
    reject_reason_text VARCHAR(255),
    completed_at TIMESTAMPTZ,
    rejected_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 3. 빠른 검색을 위한 색인(INDEX) 생성
CREATE INDEX idx_mentors_category ON mentors(category);
CREATE INDEX idx_requests_mentor_id ON mentoring_requests(mentor_id);
CREATE INDEX idx_requests_status ON mentoring_requests(status);
CREATE INDEX idx_requests_student_id ON mentoring_requests(student_id);
CREATE INDEX idx_answers_request_id ON mentoring_answers(request_id);


-- 4. 보안 설정 (Row Level Security - RLS 활성화 및 접근 정책)
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE mentors ENABLE ROW LEVEL SECURITY;
ALTER TABLE mentoring_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE mentoring_answers ENABLE ROW LEVEL SECURITY;

-- 4-1. users 정책
CREATE POLICY "users_select_policy" ON users FOR SELECT USING (true);
CREATE POLICY "users_insert_policy" ON users FOR INSERT WITH CHECK (true);
CREATE POLICY "users_update_policy" ON users FOR UPDATE USING (true);

-- 4-2. mentors 정책
CREATE POLICY "mentors_select_policy" ON mentors FOR SELECT USING (true);
CREATE POLICY "mentors_all_policy" ON mentors FOR ALL USING (true);

-- 4-3. mentoring_requests 정책
CREATE POLICY "requests_select_policy" ON mentoring_requests FOR SELECT USING (true);
CREATE POLICY "requests_insert_policy" ON mentoring_requests FOR INSERT WITH CHECK (true);
CREATE POLICY "requests_update_policy" ON mentoring_requests FOR UPDATE USING (true);
CREATE POLICY "requests_delete_policy" ON mentoring_requests FOR DELETE USING (true);

-- 4-4. mentoring_answers 정책
CREATE POLICY "answers_select_policy" ON mentoring_answers FOR SELECT USING (true);
CREATE POLICY "answers_insert_policy" ON mentoring_answers FOR INSERT WITH CHECK (true);
CREATE POLICY "answers_update_policy" ON mentoring_answers FOR UPDATE USING (true);


